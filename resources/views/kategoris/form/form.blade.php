<script>
function generateKodeFromNama() {
    var nama = document.getElementById('form-nama').value.trim();
    var kodeInput = document.getElementById('form-kode');
    
    // Only auto-generate if kode field is empty or was auto-generated
    if (nama && (!kodeInput.value || kodeInput.dataset.autoGenerated === 'true')) {
        var words = nama.split(' ').filter(function(word) { return word.trim().length > 0; });
        var kodeParts = [];
        
        words.forEach(function(word) {
            word = word.toUpperCase().trim();
            if (word.length >= 3) {
                kodeParts.push(word.substring(0, 3));
            } else {
                // Use the word as-is if it's 2 letters or less (no padding)
                kodeParts.push(word);
            }
        });
        
        var generatedKode = kodeParts.join('-');
        kodeInput.value = generatedKode;
        kodeInput.dataset.autoGenerated = 'true';
    }
}

// Initialize on page load
document.addEventListener('DOMContentLoaded', function() {
    var namaInput = document.getElementById('form-nama');
    var kodeInput = document.getElementById('form-kode');
    
    // If editing and kode exists, mark as not auto-generated (user can still edit)
    if (kodeInput.value) {
        kodeInput.dataset.autoGenerated = 'false';
    } else {
        // If new, generate kode from nama if nama exists
        if (namaInput.value) {
            generateKodeFromNama();
        }
    }
    
    // Reset auto-generated flag when user manually edits kode
    kodeInput.addEventListener('input', function() {
        this.dataset.autoGenerated = 'false';
    });
});
</script>

