        <label>Nama</label>
        <input type="text" class="form-control" id="form-nama" name="nama" required value="{{is_object($item) ? ($item->nama ?? '') : ''}}" onkeyup="generateKodeFromNama()">
        <small class="text-muted">Kode akan otomatis dibuat dari nama</small>
    </div>

    <div class="form-group">
        <label>Kode</label>
        <input type="text" class="form-control" id="form-kode" name="kode" required value="{{is_object($item) ? ($item->kode ?? '') : ''}}">
        <small class="text-muted">Dapat diedit manual jika diperlukan</small>
    </div>

    <button class="btn btn-primary mt-3">Submit</button>

